"""Publish the build preview branch or add its screenshot to release notes."""

from __future__ import annotations

import argparse
import base64
import json
import os
from pathlib import Path
import re
from urllib.error import HTTPError
from urllib.parse import quote
from urllib.request import Request, urlopen


PREVIEW_BRANCH = "launcher-preview"
RELEASE_PREVIEW_BRANCH = "release-previews"
IMAGE_NAME = "gr8-launcher-home.png"
START_MARKER = "<!-- gr8-launcher-preview:start -->"
END_MARKER = "<!-- gr8-launcher-preview:end -->"


class GitHubAPI:
    def __init__(self):
        repository = os.environ.get("GH_REPO", os.environ.get("GITHUB_REPOSITORY", ""))
        if not re.fullmatch(r"[\w.-]+/[\w.-]+", repository):
            raise ValueError("Set GH_REPO to owner/repository.")
        self.repository = repository
        self.token = os.environ.get("GH_TOKEN", "")
        if not self.token:
            raise ValueError("Set GH_TOKEN to a GitHub token with contents: write.")
        self.base_url = os.environ.get("GITHUB_API_URL", "https://api.github.com").rstrip("/")

    def request(self, method: str, path: str, payload=None, *, allow_missing=False):
        data = json.dumps(payload).encode("utf-8") if payload is not None else None
        request = Request(f"{self.base_url}/repos/{self.repository}/{path}", data=data, method=method,
                          headers={"Authorization": f"Bearer {self.token}",
                                   "Accept": "application/vnd.github+json",
                                   "Content-Type": "application/json",
                                   "X-GitHub-Api-Version": "2022-11-28",
                                   "User-Agent": "Gr8Launcher-screenshot-workflow"})
        try:
            with urlopen(request, timeout=30) as response:
                if response.status == 204:
                    return None
                return json.load(response)
        except HTTPError as error:
            if allow_missing and error.code == 404:
                return None
            raise RuntimeError(f"GitHub {method} {path} failed ({error.code}): "
                               f"{error.read().decode('utf-8', errors='replace')}") from error


def update_release_notes(body: str, image_url: str) -> str:
    block = (
        f"{START_MARKER}\n## Launcher preview\n\n"
        f"![Gr8 Launcher home screen]({image_url})\n\n"
        "Captured from this release's source with example profiles.\n"
        f"{END_MARKER}"
    )
    pattern = re.compile(re.escape(START_MARKER) + r".*?" + re.escape(END_MARKER), re.DOTALL)
    if pattern.search(body):
        return pattern.sub(lambda match: block, body)
    if START_MARKER in body or END_MARKER in body:
        raise ValueError("The preview markers in the release notes are incomplete.")
    return body + ("\n\n" if body and not body.endswith("\n\n") else "") + block + "\n"


def publish_preview(api: GitHubAPI, image: bytes, commit: str, source_branch: str, version: str) -> bool:
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ValueError("SOURCE_COMMIT must be the full built commit SHA.")
    branch_path = f"git/ref/heads/{quote(source_branch, safe='')}"

    def current_source():
        return api.request("GET", branch_path)["object"]["sha"] == commit

    # Rerunning an older build must not replace the current README preview.
    if not current_source():
        print("Skipping README preview: the source branch has newer commits.")
        return False
    reference = api.request("GET", f"git/ref/heads/{PREVIEW_BRANCH}", allow_missing=True)
    blob = api.request("POST", "git/blobs", {
        "content": base64.b64encode(image).decode("ascii"), "encoding": "base64",
    })
    metadata = json.dumps({"commit": commit, "branch": source_branch, "version": version}, indent=2) + "\n"
    tree = api.request("POST", "git/trees", {"tree": [
        {"path": IMAGE_NAME, "mode": "100644", "type": "blob", "sha": blob["sha"]},
        {"path": "source.json", "mode": "100644", "type": "blob", "content": metadata},
        {"path": "README.md", "mode": "100644", "type": "blob", "content":
         "# Launcher preview\n\nGenerated by the Windows build workflow. "
         "See `source.json` for the source commit and package version.\n"},
    ]})
    generated = api.request("POST", "git/commits", {
        "message": f"Update launcher preview for {commit[:12]}", "tree": tree["sha"],
        "parents": [reference["object"]["sha"]] if reference else [],
    })
    if not current_source():
        print("Skipping README preview: the source branch changed during publication.")
        return False
    if reference:
        api.request("PATCH", f"git/refs/heads/{PREVIEW_BRANCH}", {"sha": generated["sha"], "force": False})
    else:
        api.request("POST", "git/refs", {"ref": f"refs/heads/{PREVIEW_BRANCH}", "sha": generated["sha"]})
    print(f"Updated {PREVIEW_BRANCH} from {source_branch}@{commit[:12]}.")
    return True


def archive_release_image(api: GitHubAPI, tag: str, image: bytes) -> str:
    reference = api.request("GET", f"git/ref/heads/{RELEASE_PREVIEW_BRANCH}", allow_missing=True)
    blob = api.request("POST", "git/blobs", {
        "content": base64.b64encode(image).decode("ascii"), "encoding": "base64",
    })
    tree = api.request("POST", "git/trees", {"tree": [
        {"path": IMAGE_NAME, "mode": "100644", "type": "blob", "sha": blob["sha"]},
        {"path": "source.json", "mode": "100644", "type": "blob",
         "content": json.dumps({"tag": tag}, indent=2) + "\n"},
    ]})
    generated = api.request("POST", "git/commits", {
        "message": f"Archive launcher screenshot for {tag}", "tree": tree["sha"],
        "parents": [reference["object"]["sha"]] if reference else [],
    })
    if reference:
        api.request("PATCH", f"git/refs/heads/{RELEASE_PREVIEW_BRANCH}",
                    {"sha": generated["sha"], "force": False})
    else:
        api.request("POST", "git/refs", {
            "ref": f"refs/heads/{RELEASE_PREVIEW_BRANCH}", "sha": generated["sha"],
        })
    # Pin the notes to this commit so future image updates cannot change them.
    return f"https://raw.githubusercontent.com/{api.repository}/{generated['sha']}/{IMAGE_NAME}"


def publish_release_notes(api: GitHubAPI, tag: str, image: bytes) -> None:
    release = api.request("GET", f"releases/tags/{quote(tag, safe='')}")
    body = release.get("body") or ""
    # Check the markers before making any repository changes.
    update_release_notes(body, "preview")
    image_url = archive_release_image(api, tag, image)
    updated = update_release_notes(body, image_url)
    if updated != body:
        api.request("PATCH", f"releases/{release['id']}", {"body": updated})
    # Migrate old releases only after their notes point to the archived image.
    for asset in release["assets"]:
        if asset["name"] == IMAGE_NAME:
            api.request("DELETE", f"releases/assets/{asset['id']}")
    print(f"Release {tag} displays its screenshot in the notes without a PNG download.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    preview = commands.add_parser("preview", help="Refresh the README image branch")
    preview.add_argument("--image", type=Path, default=Path("dist") / IMAGE_NAME)
    preview.add_argument("--commit", default=os.environ.get("SOURCE_COMMIT", ""))
    preview.add_argument("--source-branch", default=os.environ.get("SOURCE_BRANCH", "main"))
    preview.add_argument("--version", default=os.environ.get("BUILD_VERSION", ""))
    release = commands.add_parser("release", help="Archive the image and embed it in release notes")
    release.add_argument("--tag", required=True)
    release.add_argument("--image", type=Path, default=Path("dist") / IMAGE_NAME)
    args = parser.parse_args()
    api = GitHubAPI()
    image = args.image.read_bytes()
    if not image.startswith(b"\x89PNG\r\n\x1a\n"):
        raise ValueError("The build preview must be a PNG image.")
    if args.command == "preview":
        publish_preview(api, image, args.commit, args.source_branch, args.version)
    else:
        publish_release_notes(api, args.tag, image)


if __name__ == "__main__":
    main()
